// Regenerate web/src/abi/*.ts from Hardhat artifacts: `npm run abi` (runs compile first).
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const hdr = "// GENERATED by scripts/export-abi.cjs from contracts/artifacts. Do not edit by hand.\n";
const out = [
  ["contracts/artifacts/contracts/BullaEscrow.sol/BullaEscrow.json", "web/src/abi/bullaEscrow.ts", "bullaEscrowAbi"],
  ["contracts/artifacts/contracts/mocks/MockERC20.sol/MockERC20.json", "web/src/abi/mockErc20.ts", "mockErc20Abi"],
  ["contracts/artifacts/contracts/mocks/MockTapeOutStandIn.sol/MockProcessor.json", "web/src/abi/mockProcessor.ts", "mockProcessorAbi"],
];
for (const [src, dst, name] of out) {
  const { abi } = JSON.parse(fs.readFileSync(path.join(root, src), "utf8"));
  fs.writeFileSync(path.join(root, dst), `${hdr}export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  console.log("wrote", dst);
}
